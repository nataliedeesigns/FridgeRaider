// Flexible recipe templates.
//
// Instead of a fixed shopping list, each recipe has "slots". A slot accepts
// specific ingredient ids or whole tags ("#veg"), and needs between `min` and
// `max` items. Slots with min >= 1 are required; the rest are filled with
// whatever the user happens to have, so one template becomes many dishes.
//
// `needsAny` lists optional slots of which at least one must be filled
// (e.g. fried rice needs *something* besides rice).
//
// Step template syntax (see engine.renderText):
//   {slot}                 -> the chosen ingredients, e.g. "carrots, peas and onion"
//   "?slot: text"          -> whole step only when the slot is filled
//   "!slot: text"          -> whole step only when the slot is empty
//   {?slot:text} {!slot:text} -> inline conditional text
//   conditions: "a|b" (any filled), "a=id1/id2" (slot contains one of those ids)

